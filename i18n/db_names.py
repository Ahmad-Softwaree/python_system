def trilang(en_value: str) -> tuple[str, str, str]:
    en = en_value or ""
    hit = TRANSLATIONS.get(en)
    if hit:
        return en, hit.get("ar") or en, hit.get("ckb") or en
    return en, en, en


def expand_row(row: dict, fields=("name",)) -> dict:
    """Turn name → name_en / name_ar / name_ckb (same for description, title, body, …)."""
    out = dict(row)
    for field in fields:
        if field not in out:
            continue
        en, ar, ckb = trilang(str(out.pop(field) or ""))
        out[f"{field}_en"] = en
        out[f"{field}_ar"] = ar
        out[f"{field}_ckb"] = ckb
    return out
